const DICTS: Record<Language, Dict> = { en, es }

export function localeForLanguage(lang: Language): string {
  return lang === 'es' ? 'es-DO' : 'en-US'
}

export function localizedSystemCategoryName(name: string, lang: Language): string {
  if (lang === 'en') return name
  const names: Record<string, string> = {
    Housing: 'Vivienda',
    Groceries: 'Supermercado',
    'Eating Out': 'Comer fuera',
    Transport: 'Transporte',
    Utilities: 'Servicios',
    Entertainment: 'Entretenimiento',
    Shopping: 'Compras',
    Health: 'Salud',
    Salary: 'Salario',
    Other: 'Otro',
    Recurring: 'Recurrente',
  }
  return names[name] ?? name
}

export function translate(
  lang: Language,
  key: string,
  params?: Record<string, string | number>
): string {
  let str = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return str
}
